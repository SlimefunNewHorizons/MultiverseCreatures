package gen;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Writes {@code gen/Parts.java} from the decompiled mod: the three static builders the forms share
 * (a jawed head, a tentacle, and the Wither the storm grows out of), lifted out of the mod's own
 * HeadModel, TentacleModel and WitherStormCommandBlockModel. The mod's code is never copied into
 * this repository; it is read from the decompiled sources every time the forms are generated.
 *
 * <p>Usage: {@code java gen.Extract <decompiled-sources-root> <output-Parts.java>}</p>
 */
public final class Extract {

    public static void main(String[] args) throws IOException {
        Path mod = Path.of(args[0]).resolve("witherstormmod/client/renderer/entity/model/witherstorm");
        String head = body(read(mod.resolve("HeadModel.java")), "public static void populateDefinition(PartDefinition root)");
        String tentacle = body(read(mod.resolve("TentacleModel.java")),
                "public static void populateDefinition(PartDefinition root, int[] length, PartPose offset)");
        String base = body(read(mod.resolve("impl/WitherStormCommandBlockModel.java")),
                "public static MeshDefinition createBaseMesh(MeshDefinition mesh, CubeDeformation def, boolean hasCenterHead, boolean hasRibcageExtension, boolean hasTail)")
                .replace("mesh.m_171576_()", "rootPart")
                .replace("return mesh;", "");
        String out = """
                package gen;

                import net.minecraft.client.model.geom.PartPose;
                import net.minecraft.client.model.geom.builders.CubeDeformation;
                import net.minecraft.client.model.geom.builders.CubeListBuilder;
                import net.minecraft.client.model.geom.builders.PartDefinition;
                import net.minecraft.util.Mth;

                /** Generated by gen.Extract from the decompiled mod; not part of the repository. */
                final class Parts {
                   static void head(PartDefinition root) {
                %s
                   }

                   static void tentacle(PartDefinition root, int[] length, PartPose offset) {
                %s
                   }

                   static void witherBase(PartDefinition rootPart, CubeDeformation def, boolean hasCenterHead, boolean hasRibcageExtension, boolean hasTail) {
                %s
                   }

                   private Parts() {
                   }
                }
                """.formatted(head, tentacle, base);
        Files.writeString(Path.of(args[1]), out, StandardCharsets.UTF_8);
    }

    private static String read(Path file) throws IOException {
        return Files.readString(file, StandardCharsets.UTF_8);
    }

    /** The body of the method with this signature, between its braces. */
    private static String body(String source, String signature) {
        int at = source.indexOf(signature);
        if (at < 0) {
            throw new IllegalStateException("not found in the decompiled mod: " + signature);
        }
        int open = source.indexOf('{', at);
        int depth = 0;
        for (int i = open; i < source.length(); i++) {
            char c = source.charAt(i);
            if (c == '{') depth++;
            if (c == '}' && --depth == 0) {
                return source.substring(open + 1, i);
            }
        }
        throw new IllegalStateException("unbalanced braces after " + signature);
    }

    private Extract() {
    }
}
